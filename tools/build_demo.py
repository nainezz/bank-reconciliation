"""Rebuild index.html, the sample report served on GitHub Pages."""

from decimal import Decimal
from pathlib import Path

from recon import load_transactions, reconcile
from recon.report import write_html

ROOT = Path(__file__).resolve().parent.parent

bank = load_transactions(ROOT / "sample_data" / "bank_statement.csv", "B")
book = load_transactions(ROOT / "sample_data" / "cashbook.csv", "L")
result = reconcile(bank, book, bank_balance=Decimal("160833.50"), book_balance=Decimal("168801.00"))
write_html(
    result, ROOT / "index.html",
    title="Jamii Traders Ltd: bank reconciliation",
    period="November 2026 (sample data)",
    banner='Sample report generated by <a href="https://github.com/nainezz/bank-reconciliation">bank-reconciliation</a>, '
           'a Python tool by <a href="https://nainezz.github.io/portfolio/">Nainezz</a>',
)
print("wrote index.html")
